// Language Switcher Function
function applyLanguage(lang) {
  if (!translations[lang]) lang = 'en';
  localStorage.setItem('mindcare_language', lang);

  const langDict = translations[lang] || translations['en'];
  
  // Update elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (langDict[key]) {
      el.textContent = langDict[key];
    }
  });

  // Update elements with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (langDict[key]) {
      el.setAttribute('placeholder', langDict[key]);
    }
  });

  // Update select dropdowns if present
  const langSelect = document.getElementById('global-lang-select');
  if (langSelect && langSelect.value !== lang) {
    langSelect.value = lang;
  }

  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang, dict: langDict } }));
}

document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('mindcare_language') || 'en';
  applyLanguage(savedLang);

  const langSelect = document.getElementById('global-lang-select');
  if (langSelect) {
    langSelect.value = savedLang;
    langSelect.addEventListener('change', (e) => {
      applyLanguage(e.target.value);
    });
  }
});
